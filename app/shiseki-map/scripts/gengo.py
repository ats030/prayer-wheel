def _spans(text):
    """{元号: (開始年, 最終年)}。最終年は次の元号の開始年(改元の年)。

    「空」は元号のない期間の始まり(白雉と朱鳥の後)、末尾の「終」は系列の終わりを示す。
    """
    pairs = [(m.group(1), int(m.group(2))) for m in re.finditer(r"(\D+?)(\d+)", re.sub(r"\s", "", text))]
    return {name: (start, pairs[i + 1][1]) for i, (name, start) in enumerate(pairs[:-1]) if name != "空"}


SPANS = {**_spans(_EARLY), **_spans(_SOUTH), **_spans(_NORTH), **_spans(_LATE)}

_KANJI_DIGITS = {c: i for i, c in enumerate("〇一二三四五六七八九")}
_NAME_PATTERN = "|".join(sorted(map(re.escape, SPANS), key=len, reverse=True))
# 「寛永元（1624）年」のように年の前に括弧書きが挟まる表記も読む。
YEAR_RE = re.compile(r"(" + _NAME_PATTERN + r")\s*(元|[0-9０-９]{1,2}|[〇一二三四五六七八九十]{1,3})\s*(?:[（(][^）)]*[）)])?\s*年(?!間|代)")
# 「元亀・天正年間」は並べた元号すべてを年間として読む。
PERIOD_RE = re.compile(r"((?:(?:" + _NAME_PATTERN + r")\s*[・、]\s*)*(?:" + _NAME_PATTERN + r"))\s*年間")
NAME_RE = re.compile(_NAME_PATTERN)


def _number(text):
    if text == "元":
        return 1
    if text.isdigit():
        return int(text)
    if "十" in text:
        tens, _, ones = text.partition("十")
        return (_KANJI_DIGITS.get(tens, 1) if tens else 1) * 10 + (_KANJI_DIGITS.get(ones, 0) if ones else 0)
    if len(text) == 1:
        return _KANJI_DIGITS[text]
    return None


def gengo_spans(value):
    """値に書かれた元号表記ごとに (元号, 最初の年, 最後の年) を返す。範囲外の年数は None を返す。"""
    found = []
    for match in YEAR_RE.finditer(value):
        name, n = match.group(1), _number(match.group(2))
        start, end = SPANS[name]
        year = start + n - 1 if n else None
        found.append((name, year, year) if year and year <= end else (name, None, None))
    for match in PERIOD_RE.finditer(value):
        for name in NAME_RE.findall(match.group(1)):
            found.append((name, *SPANS[name]))
    return found
