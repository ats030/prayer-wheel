#!/usr/bin/env python3
"""Synchronize and verify thin adapters for the canonical AGENTS.md."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


CLAUDE_TEMPLATE = """<!-- Generated by scripts/sync-agent-context.sh. Do not edit. -->
@{agents_path}
@RTK.md
"""


def paths(home: Path) -> tuple[Path, Path, Path]:
    return (
        home / "AGENTS.md",
        home / ".claude" / "CLAUDE.md",
        home / ".config" / "opencode" / "opencode.json",
    )


def expected_claude(agents_path: Path) -> str:
    return CLAUDE_TEMPLATE.format(agents_path=agents_path)


def load_opencode(path: Path) -> dict[str, object]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {"$schema": "https://opencode.ai/config.json"}
    except json.JSONDecodeError as exc:
        raise ValueError(f"invalid JSON in {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"expected a JSON object in {path}")
    return value


def expected_opencode(path: Path, agents_path: Path) -> dict[str, object]:
    config = load_opencode(path)
    raw_instructions = config.get("instructions", [])
    if not isinstance(raw_instructions, list) or not all(
        isinstance(item, str) for item in raw_instructions
    ):
        raise ValueError(f"instructions must be a string array in {path}")
    canonical = str(agents_path)
    config["instructions"] = [
        canonical,
        *(item for item in raw_instructions if item != canonical),
    ]
    return config


def render_json(value: dict[str, object]) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def sync(home: Path) -> int:
    agents_path, claude_path, opencode_path = paths(home)
    if not agents_path.is_file():
        print(f"missing canonical file: {agents_path}", file=sys.stderr)
        return 1

    try:
        opencode = expected_opencode(opencode_path, agents_path)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1

    claude_path.parent.mkdir(parents=True, exist_ok=True)
    opencode_path.parent.mkdir(parents=True, exist_ok=True)
    claude_path.write_text(expected_claude(agents_path), encoding="utf-8")
    opencode_path.write_text(render_json(opencode), encoding="utf-8")
    print(f"updated {claude_path}")
    print(f"updated {opencode_path}")
    return 0


def check(home: Path) -> int:
    agents_path, claude_path, opencode_path = paths(home)
    errors: list[str] = []
    if not agents_path.is_file():
        errors.append(f"missing canonical file: {agents_path}")

    try:
        actual_claude = claude_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        errors.append(f"missing generated adapter: {claude_path}")
    else:
        if actual_claude != expected_claude(agents_path):
            errors.append(f"generated adapter drifted: {claude_path}")

    try:
        actual_opencode = load_opencode(opencode_path)
        wanted_opencode = expected_opencode(opencode_path, agents_path)
    except ValueError as exc:
        errors.append(str(exc))
    else:
        if actual_opencode != wanted_opencode:
            errors.append(f"canonical instruction missing or misordered: {opencode_path}")

    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print("run scripts/sync-agent-context.sh to repair adapters", file=sys.stderr)
        return 1
    print("agent context adapters are in sync")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("sync", "check"))
    parser.add_argument(
        "--home",
        type=Path,
        default=Path.home(),
        help="home directory to operate on (used by tests)",
    )
    args = parser.parse_args()
    return sync(args.home.resolve()) if args.mode == "sync" else check(args.home.resolve())


if __name__ == "__main__":
    raise SystemExit(main())
